"""Regenerate app/engine/messages_catalog.py from the frontend string catalog, so exports and the
interface say findings in exactly the same words. Run after editing fnd.* keys in strings_cp.ts."""
import re, os, json

SRC = os.path.join(os.path.dirname(__file__), "..", "..", "frontend", "src", "lib", "strings_cp.ts")
OUT = os.path.join(os.path.dirname(__file__), "..", "app", "engine", "messages_catalog.py")

s = open(SRC, encoding="utf-8").read()
marks = {"en": "export const cpEn", "ar": "export const cpAr", "fr": "export const cpFr"}
pos = sorted(((s.index(m), lang) for lang, m in marks.items()))
cat = {}
for (i, lang), nxt in zip(pos, pos[1:] + [(len(s), None)]):
    seg = s[i:nxt[0]]
    cat[lang] = dict(re.findall(r'"(fnd\.[^"]+)": "(.*)",\s*$', seg, re.M))
counts = {k: len(v) for k, v in cat.items()}
assert len(set(counts.values())) == 1, counts
with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("# Generated by scripts/gen_messages.py from frontend/src/lib/strings_cp.ts — do not edit by hand.\n")
    fh.write("FND = " + json.dumps(cat, ensure_ascii=False, indent=1, sort_keys=True) + "\n")
print("wrote", OUT, counts)
